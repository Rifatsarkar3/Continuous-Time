"""E1: rebuild PRONOSTIA (17 bearings) from raw and audit both processed datasets."""
import argparse
import datetime
import json
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from certalarm import paths  # noqa: E402
from certalarm.data import pronostia, xjtu  # noqa: E402

NAN = float("nan")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--rebuild", action="store_true")
    a = ap.parse_args()
    out_dir = paths.DATA / "pronostia"
    man_path = out_dir / "manifest.json"
    commit = subprocess.run(["git", "rev-parse", "HEAD"], cwd=paths.ROOT, capture_output=True,
                            text=True).stdout.strip()
    generated = datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds")
    rebuilt = a.rebuild or not man_path.exists()
    if rebuilt:
        manifest = pronostia.build_all(paths.PHM2012, out_dir)
    else:
        manifest = json.loads(man_path.read_text())
    rep = {"provenance": {"generated_at_utc": generated, "git_commit": commit,
                          "pronostia_rebuilt_this_run": rebuilt},
           "pronostia_manifest": manifest,
           "pronostia_processed_audit": pronostia.audit_processed(paths.PHM2012, paths.PRONOSTIA_PROCESSED),
           "xjtu_processed_audit": xjtu.audit_processed(paths.XJTU_PROCESSED, paths.XJTU_RAW)}
    paths.RESULTS.mkdir(exist_ok=True)
    (paths.RESULTS / "e1_data_audit.json").write_text(json.dumps(rep, indent=2))
    lines = ["# Data integrity audit (generated by experiments/e1_data_audit.py)", "",
             f"Generated {generated} at commit {commit[:10]}.", "",
             "## PRONOSTIA rebuilt from raw", "", "| Bearing | Source | Condition | Windows |", "|---|---|---|---|"]
    lines += [f"| {k} | {v['source']} | {v['condition']} | {v['n']} |" for k, v in manifest.items()]
    lines += ["", "## Dual-Stream processed PRONOSTIA vs raw", "",
              "Checked windows: first, up to three interior quartiles, and the last raw snapshot. "
              "Only bearings present in the Dual-Stream Processed_PRONOSTIA folder are listed "
              "(it covers 8 of the 17 bearings by design).", "",
              "| Bearing | Raw | Processed | Extra | RMS last raw (g) | RMS extra, median (g) | Verdict |",
              "|---|---|---|---|---|---|---|"]
    for k, v in rep["pronostia_processed_audit"].items():
        lines.append(f"| {k} | {v['n_raw']} | {v['n_processed']} | {v.get('extra_windows', '')} | "
                     f"{v.get('rms_last_raw', NAN):.2f} | {v.get('rms_extra_median', NAN):.2f} | {v['verdict']} |")
    lines += ["", "## XJTU-SY processed vs raw", "",
              "Checked: window count, and the first two windows of files 1, 2, middle and last (numeric order).", "",
              "| Bearing | Files | Windows | Verdict |", "|---|---|---|---|"]
    lines += [f"| {k} | {v['files']} | {v['windows']} | {v['verdict']} |" for k, v in rep["xjtu_processed_audit"].items()]
    (paths.RESULTS / "e1_data_audit.md").write_text("\n".join(lines) + "\n")
    bad = {k: v["verdict"] for k, v in rep["pronostia_processed_audit"].items() if v["verdict"] != "ok"}
    bad_x = {k: v["verdict"] for k, v in rep["xjtu_processed_audit"].items() if v["verdict"] != "ok"}
    print("PRONOSTIA manifest:", len(manifest), "bearings",
          "(rebuilt this run)" if rebuilt else "(cached)")
    print("PRONOSTIA processed issues:", bad)
    print("XJTU processed issues:", bad_x)


if __name__ == "__main__":
    main()
